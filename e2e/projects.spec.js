import { test, expect } from '@playwright/test'

test.beforeEach(async({page})=>{await page.goto('/cong-viec');await page.evaluate(()=>localStorage.clear());await page.reload();await page.getByRole('tab',{name:'Dự án'}).click()})

test('vòng đời tạo, sửa, lưu trữ và xóa dự án',async({page})=>{
 await page.getByRole('button',{name:'Tạo dự án'}).first().click()
 let drawer=page.getByRole('dialog',{name:'Tạo dự án'})
 await drawer.getByLabel('Tên dự án *').fill('Kế hoạch thử nghiệm')
 await drawer.getByLabel('Mô tả').fill('Kiểm thử toàn bộ vòng đời')
 await drawer.getByRole('button',{name:'Lưu dự án'}).click()
 const card=page.locator('.project-solid-card').filter({hasText:'Kế hoạch thử nghiệm'})
 await expect(card).toBeVisible()
 await card.getByRole('button',{name:'Thao tác Kế hoạch thử nghiệm'}).click()
 await page.getByRole('menuitem',{name:'Chỉnh sửa'}).click()
 drawer=page.getByRole('dialog',{name:'Chỉnh sửa dự án'})
 await drawer.getByLabel('Tên dự án *').fill('Kế hoạch đã sửa')
 await drawer.getByRole('button',{name:'Lưu dự án'}).click()
 const edited=page.locator('.project-solid-card').filter({hasText:'Kế hoạch đã sửa'})
 await edited.getByRole('button',{name:'Thao tác Kế hoạch đã sửa'}).click()
 await page.getByRole('menuitem',{name:'Lưu trữ'}).click()
 await expect(edited).toBeHidden()
 await page.getByLabel('Hiện dự án lưu trữ').check()
 await expect(edited).toBeVisible()
 await edited.getByRole('button',{name:'Thao tác Kế hoạch đã sửa'}).click()
 await page.getByRole('menuitem',{name:'Xóa'}).click()
 await page.getByRole('dialog',{name:'Xóa dự án?'}).getByRole('button',{name:'Xóa dự án'}).click()
 await expect(edited).toBeHidden()
 await expect(page.getByText('Đã xóa dự án và cập nhật nhiệm vụ.')).toBeVisible()
})
